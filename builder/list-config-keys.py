#!/usr/bin/env python3
"""List every perf.cfg key the code reads, and keep docs/PERF-CFG-KEYS.md in step with the code.

  python builder/list-config-keys.py            print the table
  python builder/list-config-keys.py --write    rewrite docs/PERF-CFG-KEYS.md
  python builder/list-config-keys.py --check    exit 1 if that file is stale (for CI and review)

Keys are found where the code asks for them: melee_nx_opt("key", default) (an optimization switch,
logged at boot and turned off by `opt_safe 1`), melee_nx_perf_int("key", default) (a plain value)
and their KartPadNX names kartpad_opt / kartpad_perf_int, which the native renderer calls. The keys
melee_nx_perf_init parses itself are listed in NAMED and checked against the source.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / 'docs' / 'PERF-CFG-KEYS.md'
SOURCES = [ROOT / 'switch', ROOT / 'builder' / 'integrate-deko.py']
CALL = re.compile(r'\b(melee_nx_opt|kartpad_opt|melee_nx_perf_int|kartpad_perf_int)\s*\(\s*"([a-z0-9_]+)"\s*,\s*([^)]+?)\s*\)')

# Parsed by name in melee_nx_perf_init (switch/src/perf_switch.cpp): key -> (default, values).
NAMED = {
    'affinity': ('baseline', 'baseline, main, split, tuned (docs: PERFORMANCE.md)'),
    'compile_workers': ('1', '1 or 2 pipeline compilers (NVK renderer)'),
    'monolithic_cache': ('0', '1 shares one Vulkan pipeline cache (NVK renderer)'),
    'launch_warm': ('1', '0 skips the startup shader warm-up (NVK renderer)'),
    'gx_skip_unready': ('0', '1 skips draws whose pipeline is not ready (NVK renderer)'),
    'warm_helpers': ('0', '0-2 extra warm-up compilers (NVK renderer)'),
    'uber': ('0', '0 off, 1 hybrid, 2 always; measured too slow on the GPU (NVK renderer)'),
}
# What the keys found by CALL do (they have no entry in NAMED). A key without one lists an empty cell.
DESCRIPTIONS = {
    'gpu_steady_v9': '1 applies the v9 GPU submission policy to every frame, not only scene loads (deko3d renderer)',
    'opt_safe': '1 turns every opt off except those the file sets',
    'prof_hz': 'samples per second per thread, at most 4000 (sampling profiler, PERFORMANCE.md)',
    'prof_seconds': 'seconds to record; 0 never starts the profiler (sampling profiler)',
    'prof_start': 'seconds after launch before recording starts (sampling profiler)',
    'texture_cmpr_bc1': '1 keeps CMPR textures compressed as BC1, an eighth of the RGBA8 bytes (deko3d renderer)',
}
SKIP_DIRS = {'uam', 'build', 'ref'}


def source_files():
    for entry in SOURCES:
        if entry.is_file():
            yield entry
            continue
        for path in sorted(entry.rglob('*')):
            if path.suffix in ('.cpp', '.c', '.h', '.hpp', '.inc') and not (SKIP_DIRS & set(path.relative_to(ROOT).parts)):
                yield path


def find_keys():
    found = {}
    for path in source_files():
        for number, line in enumerate(path.read_text(encoding='utf-8', errors='replace').splitlines(), 1):
            for function, key, default in CALL.findall(line):
                kind = 'opt' if function.endswith('opt') else 'setting'
                where = f'{path.relative_to(ROOT).as_posix()}:{number}'
                entry = found.setdefault(key, {'kind': kind, 'default': default, 'where': []})
                if where not in entry['where']:
                    entry['where'].append(where)
    perf = (ROOT / 'switch' / 'src' / 'perf_switch.cpp').read_text(encoding='utf-8')
    for key, (default, values) in NAMED.items():
        if f'"{key}"' not in perf:
            sys.exit(f'NAMED lists {key}, which perf_switch.cpp no longer parses: update builder/list-config-keys.py')
        found[key] = {'kind': 'setting', 'default': default, 'where': ['switch/src/perf_switch.cpp'], 'values': values}
    for key, entry in found.items():
        entry.setdefault('values', DESCRIPTIONS.get(key, ''))
    return dict(sorted(found.items()))


def render(keys):
    lines = [
        '# perf.cfg keys',
        '',
        'Generated by `python builder/list-config-keys.py --write`; do not edit by hand.',
        '',
        '`sdmc:/switch/melee-nx/perf.cfg` holds one `key value` per line (decimal or `0x` hex), read once at',
        'startup. Without the file every key has its default.',
        '',
        '- **opt**: an optimization switch. The runtime log shows each as `[opt] key=value (source)`.',
        '  `opt_safe 1` turns every opt off except those the file sets explicitly.',
        '- **setting**: a plain value.',
        '',
        f'{len(keys)} keys.',
        '',
        '| Key | Kind | Default | Values | Read in |',
        '|---|---|---|---|---|',
    ]
    for key, entry in keys.items():
        where = ', '.join(f'`{w}`' for w in entry['where'][:3]) + (' …' if len(entry['where']) > 3 else '')
        lines.append(f"| `{key}` | {entry['kind']} | `{entry['default']}` | {entry.get('values', '')} | {where} |")
    lines.append('')
    return '\n'.join(lines)


def main():
    text = render(find_keys())
    if '--write' in sys.argv:
        DOC.write_text(text, encoding='utf-8', newline='\n')
        print(f'wrote {DOC.relative_to(ROOT)}')
    elif '--check' in sys.argv:
        if not DOC.is_file() or DOC.read_text(encoding='utf-8') != text:
            sys.exit('docs/PERF-CFG-KEYS.md is stale: run python builder/list-config-keys.py --write')
        print('docs/PERF-CFG-KEYS.md is current')
    else:
        print(text)


if __name__ == '__main__':
    main()
