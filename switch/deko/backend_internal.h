// Internal state of the native deko3d command adapter, shared by its four parts:
//
//   backend_objects.cpp    object registries: buffers and their staging generations, upload
//                          memory, bind group layouts and groups, buffer mapping and readback
//   backend_pipelines.cpp  shader modules, WGSL -> native stage compilation, render pipelines
//   backend_commands.cpp   command encoders and render passes: recording, draw state, copies,
//                          queue writes and submission
