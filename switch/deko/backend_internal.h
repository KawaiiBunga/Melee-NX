template <class F> void record(WGPUCommandEncoder e, F &&f) {
  Lock l(mutex);
  required(encoders, e, __func__)->emplace_back(std::forward<F>(f));
}
template <class F> void record_pass(WGPURenderPassEncoder p, F &&f) {
  Lock l(mutex);
  required(passes, p, __func__).commands->emplace_back(std::forward<F>(f));
}

