// Frame helpers: a full barrier, open the frame if needed, drain the queue (CPU readback).
inline void barrier(uint32_t extraInvalidations = 0) {
  dkCmdBufBarrier(R.cmd, DkBarrier_Full,
                 DkInvalidateFlags_Image | DkInvalidateFlags_L2Cache | extraInvalidations);
}
inline void open() {
  if (!R.frameOpen) {
    frame_open();
    objects_frame_start();
  }
}
inline void idle() {
  if (R.frameOpen)
    submit("CPU readback");
  if (R.queue)
    dkQueueWaitIdle(R.queue);
}

// GPU memory with a fence for its last recorded use (backend_objects.cpp).
struct Allocation {
  Block mem;
  DkFence fence{};
  bool pending = false;
  uint64_t pendingAfterSubmit = 0;
  ~Allocation() {
    if (mem)
      block_free_deferred(mem.block);
  }
  bool ready() {
    // Recording SignalFence leaves an empty fence, or the completed fence from
    // the previous use, untouched. Only QueueSubmit populates its new value.
    // Polling it before that submit can wrongly recycle an upload still named
    // by queued GPU copies and replace its bytes with a later upload.
    return !pending || (submit_stats().submits >= pendingAfterSubmit &&
                        dkFenceWait(&fence, 0) == DkResult_Success);
  }
  void used() {
    pendingAfterSubmit = submit_stats().submits + 1;
    dkCmdBufSignalFence(R.cmd, &fence, true);
    pending = true;
  }
};
std::shared_ptr<Allocation> allocation(uint32_t bytes, const char *label);
std::shared_ptr<Allocation> upload_allocation(uint32_t bytes);
void retire_uploads();
struct Buffer {
  Block mem; // alias of active->mem; stable GPU buffers do not rotate
  std::shared_ptr<Allocation> active;
  std::vector<std::shared_ptr<Allocation>> versions;
  uint64_t size = 0, usage = 0;
  int refs = 1;
  void prepare_map() {
    // A recorded copy pins its exact generation. Reuse a generation only after
    // both CPU command ownership and the native copy fence have released it.
    for (auto &a : versions) {
      const long ownRefs = a == active ? 2 : 1;
      if (a.use_count() == ownRefs && a->ready()) {
        active = a;
        mem = a->mem;
        return;
      }
    }
    active = allocation(size, "mapped staging generation");
    versions.push_back(active);
    mem = active->mem;
  }
};
extern std::unordered_map<WGPUBuffer, std::shared_ptr<Buffer>> buffers;

