template <class Map, class Handle>
auto &required(Map &objects, Handle handle, const char *operation) {
  auto it = objects.find(handle);
  if (it == objects.end())
    fatal("Missing native object %p in %s", static_cast<const void *>(handle), operation);
  return it->second;
}
