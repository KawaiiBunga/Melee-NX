//
// Dawn Null supplies reference-counted API handles only; every graphics command executes on
// Maxwell through deko3d. WGSL shader modules and render pipelines are not even Dawn objects: their
// handles are the adapter's own (backend_pipelines.cpp). The __wrap_wgpu* functions replace the Dawn
// entry points at link time (wrap-symbols.txt, generated by builder/integrate-deko.py from these
// files). Recorded commands own their resources until submission.
//
